/**
 * Monochrome, because a brand colour would have to answer to both themes and
 * JetBrains' own is black. The shape is what a reader recognises.
 */
export function PlaceMark({
  place,
  className = "size-4 shrink-0",
}: {
  place: SitePath;
  className?: string;
}) {
  if (place === PATHS.editor) {
    return (
      <img src="/favicon.svg" alt="" data-mark={place} className={className} />
    );
  }

  const mark = MARKS[place];
  if (!mark) {
    return null;
  }

  return (
    <svg
      viewBox={mark.viewBox}
      fill="currentColor"
      fillRule="evenodd"
      aria-hidden
      data-mark={place}
      className={className}
    >
      <path d={mark.d} />
    </svg>
  );
}
